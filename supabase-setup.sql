create table if not exists public.cadets (
  user_id uuid primary key references auth.users(id) on delete cascade,
  cadet_id text unique not null,
  phone text not null check (phone ~ '^[0-9]{10}$'),
  joining_year integer not null,
  wing text not null check (wing in ('SDIA','SWIA')),
  rank text not null,
  full_name text not null,
  cadet_year integer not null default 1,
  status text not null default 'active' check (status in ('active','inactive','cancelled','pending')),
  created_at timestamptz not null default now()
);

create table if not exists public.ncc_applications (
  id bigint generated by default as identity primary key,
  name text not null,
  department text,
  roll text,
  semester text,
  gender text,
  mobile text,
  email text,
  height text,
  blood_group text,
  hostel_status text,
  emergency_contact text,
  a_certificate text,
  sports_certificate text,
  cultural_certificate text,
  medical_issues text,
  skills text,
  reason text,
  status text not null default 'pending',
  submitted_at timestamptz not null default now()
);

create table if not exists public.notices (
  id bigint generated by default as identity primary key,
  title text not null,
  content text,
  published_by text default 'ANO',
  media_url text,
  media_type text,
  expires_at timestamptz,
  created_at timestamptz not null default now()
);

alter table public.cadets enable row level security;
alter table public.ncc_applications enable row level security;
alter table public.notices enable row level security;

drop policy if exists "Cadets insert own profile" on public.cadets;
create policy "Cadets insert own profile" on public.cadets for insert to authenticated
with check (auth.uid() = user_id);

drop policy if exists "Cadets read own profile" on public.cadets;
create policy "Cadets read own profile" on public.cadets for select to authenticated
using (auth.uid() = user_id);

drop policy if exists "Public submit application" on public.ncc_applications;
create policy "Public submit application" on public.ncc_applications for insert to anon, authenticated
with check (status = 'pending');

drop policy if exists "Public read notices" on public.notices;
create policy "Public read notices" on public.notices for select to anon, authenticated
using (true);
